"""Generate presentation-only Crew identities and history from the approved review.

Never edits the canonical card catalog, rules state or gameplay definitions.
"""
import ast
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRIVATE = ROOT / 'game/OldWest/Source/OldWestGame/Private'

def literal(value):
    return json.dumps(value, ensure_ascii=False)

def compact_lines(slug, history, compact):
    """Use authored summaries, never truncate historical claims to fit the UI."""
    note = compact['notes'][slug]
    assert note['history_lesson_sha256'] == hashlib.sha256(
        history['history_lesson'].encode('utf-8')).hexdigest(), 'Review summary after lesson change: ' + slug
    lines = note['lines']
    assert len(lines) == 3 and all(isinstance(line, str) and '\n' not in line
                                 and 0 < len(line.encode('utf-8')) <= 52 for line in lines), slug
    return '\n'.join(lines)

def main():
    module = ast.parse((ROOT / 'scripts/build_crew_review.py').read_text())
    roster = next(ast.literal_eval(n.value) for n in module.body if isinstance(n, ast.Assign)
                  and any(isinstance(t, ast.Name) and t.id == 'ROSTER' for t in n.targets))
    page = (ROOT / 'art/western/crew/review-v002/index.html').read_text()
    gallery = json.loads(re.search(r'<script>const data=(.*?);\nconst g=', page, re.S).group(1))
    by_slug = {entry['slug']: entry for entry in gallery}
    assert len(by_slug) == sum(map(len, roster.values())) == 46
    compact = json.loads((ROOT / 'research/crew-history-audit/compact-display-notes.json').read_text())
    assert set(compact['notes']) == set(by_slug), 'Compact notes must cover every Crew identity exactly once'
    assert compact['maximum_utf8_bytes_per_line'] == 52
    native = {'quanah-parker': 'Quanah', 'lozen': 'Lozen', 'sarah-winnemucca': 'Sarah'}
    overrides_path = ROOT/'art/western/crew/playable-overrides.json'
    overrides = json.loads(overrides_path.read_text()) if overrides_path.exists() else {}
    assert set(overrides) <= set(by_slug)-set(native)
    rows, notes = [], []
    for canonical, slugs in roster.items():
        for copy, slug in enumerate(slugs, 1):
            entry = by_slug[slug]
            name = native.get(slug, ''.join(word.title() for word in slug.split('-')))
            directory = '/Game/Art/Western/' + (name if slug in native else 'Crew/' + name)
            mesh_directory = directory
            if slug in overrides:
                override = overrides[slug]
                verification = ROOT/override['verification']
                assert hashlib.sha256(verification.read_bytes()).hexdigest() == override['verification_sha256']
                report = json.loads(verification.read_text())
                assert report['ok'] and report['existing_content_unchanged']
                mesh_directory = override['mesh_directory']
                assert mesh_directory.startswith(directory+'/') and report['destination'] == mesh_directory
                for path, digest in report['content_sha256'].items():
                    assert hashlib.sha256((ROOT/path).read_bytes()).hexdigest() == digest, path
            rows.append('    {' + ', '.join([literal(canonical), str(copy), literal(slug), literal(entry['name']), literal(name),
                literal(mesh_directory + '/SK_' + name + '.SK_' + name),
                literal(directory + '/PA_' + name + '.PA_' + name),
                literal(mesh_directory + '/Animations/'), 'true' if slug in native else 'false']) + '},')
            history = entry['history']; sources = history['sources']
            assert history['history_lesson'] and history['date_scope'] and history['location_scope'] and sources
            identity = 'Fictional composite' if history['identity_type'].startswith('fictional') else 'Historical person'
            title = entry['name'] + ' — ' + identity
            attribution = (history['date_scope'] + ' · ' + history['location_scope']
                           + '\n\nFull historical note:\n' + history['history_lesson'] + '\n\n') + '\n\n'.join(
                source['title'] + '\n' + source['url'] + '\n' + source['supports'] for source in sources)
            notes.append('    {' + ', '.join(map(literal, [slug, title, compact_lines(slug, history, compact), sources[0]['title'], sources[0]['url'], attribution])) + '},')
    header = '''#pragma once
#include <string_view>

// Generated by scripts/generate_crew_presentation_catalog.py from the approved
// 46-copy roster. Presentation sidecar metadata only; never a rules catalog.
namespace OldWestCrew {
struct FEntry {
    const char* Canonical;
    int Copy;
    const char* Visual;
    const char* Name;
    const char* AssetName;
    const char* Mesh;
    const char* Physics;
    const char* Animations;
    bool Native;
};
inline constexpr FEntry Entries[] = {
ROWS
};
inline const FEntry* ForVisual(std::string_view visual) {
    for (const auto& entry : Entries) if (visual == entry.Visual) return &entry;
    return nullptr;
}
inline const FEntry* ForCopy(std::string_view canonical, int copy = 1) {
    for (const auto& entry : Entries) if (canonical == entry.Canonical && copy == entry.Copy) return &entry;
    return nullptr;
}
inline const FEntry* Resolve(std::string_view canonical, std::string_view visual) {
    const auto* entry = ForVisual(visual);
    return entry && canonical == entry->Canonical ? entry : nullptr;
}
inline const FEntry* ForAssetName(std::string_view name) {
    for (const auto& entry : Entries) if (name == entry.AssetName) return &entry;
    return nullptr;
}
}
'''.replace('ROWS', '\n'.join(rows))
    (PRIVATE / 'OldWestCrewCatalog.h').write_text(header)
    (PRIVATE / 'OldWestCrewHistory.inl').write_text('// Generated sourced history; see generate_crew_presentation_catalog.py.\n' + '\n'.join(notes) + '\n')
    print('Generated 46 distinct cosmetic identities and 46 sourced history notes')

if __name__ == '__main__':
    main()
